/// The year, manufacturer and model, separated by spaces, for a known ordinal.
pub fn name(ordinal: i64) -> Option<String> {
    CARS.binary_search_by_key(&ordinal, |c| c.0).ok().map(|i| format!("{} {} {}", CARS[i].1, CARS[i].2, CARS[i].3))
}

